export function earthHorizonCityscape(locationId: string): EarthHorizonCityscapeDefinition | null {
  return CITYSCAPES[locationId] ?? null;
}

function cityscape(
  kind: EarthHorizonCityscapeDefinition['kind'],
  far: readonly SkylinePoint[],
  near: readonly SkylinePoint[],
  atmosphereHueDegrees: number,
  lightHueDegrees: number,
  lightDensity: EarthHorizonLightDensity,
): EarthHorizonCityscapeDefinition {
  return {
    kind,
    farRidgeClipPath: skylinePolygon(far),
    nearRidgeClipPath: skylinePolygon(near),
    atmosphereHueDegrees,
    lightHueDegrees,
    lightDensity,
  };
}

function skylinePolygon(points: readonly SkylinePoint[]): string {
  const coordinates = points.map(([x, y]) => `${x.toFixed(2)}% ${y.toFixed(2)}%`);

  return `polygon(0% 100%, ${coordinates.join(', ')}, 100% 100%)`;
}
